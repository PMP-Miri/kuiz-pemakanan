import {publicStageState,participantHome,screenMarkup,projectionGuide,hostDisplayNotice} from '../src/presentation.js';
import {escapeHTML as e,rankRows} from '../src/core.js';

export function runPresentationTests(){
 const names=[];
 const assert=(ok,name)=>{if(!ok)throw Error('GAGAL: '+name);names.push(name);};
 const clone=x=>JSON.parse(JSON.stringify(x));
 const raw={room:{id:'PRIVATE_ROOM',owner_id:'PRIVATE_OWNER',code:'1234ABCD',title:'Cabaran Ceria',theme:'aurora',phase:'normal',status:'question',current_index:0,total:3,opened_at:'2026-10-28T00:00:00Z',settings:{leaderboard:true,winners:2,speedBonus:true}},players:[{id:'PRIVATE_ID',name:'Nadia',participant_code:'SECRET_CODE',user_id:'PRIVATE_UID',answered:1,correct:1,points:1000,ms:200,answered_current:true},{name:'Amir',participant_code:'OTHER_SECRET',answered:1,correct:1,points:1000,ms:200},{name:'Belum jawab',answered:0,correct:0,points:0,ms:0}],question:{id:'q1',text:'Pilihan terbaik?',options:['Air kosong','Minuman manis'],seconds:20,topic:'Air',correct:0,explanation:'PRIVATE_EXPLANATION',source:'https://example.org',sourceLabel:'PRIVATE_SOURCE'},answered:2,distribution:{0:2},mine:{selected:0},player:{participant_code:'MY_SECRET'},my_stats:{correct:1},server_now:'2026-10-28T00:00:01Z'};
 const before=JSON.stringify(raw),question=publicStageState(raw),s=JSON.stringify(question);
 assert(!s.includes('SECRET')&&!s.includes('PRIVATE'),'Question: tiada medan peribadi / jawapan');
 assert(!('player' in question)&&!('mine' in question)&&!('my_stats' in question),'Tiada keputusan sendiri dalam model TV');
 assert(!('id' in question.room)&&!('speedBonus' in question.room.settings),'Room whitelist');
 assert(question.players.every(p=>Object.keys(p).join(',')==='name'),'Question: hanya nama awam');
 assert(!('correct' in question.question)&&!('source' in question.question),'Jawapan disembunyikan semasa soalan');
 assert(Object.keys(question.distribution).length===0,'Undian disembunyikan sebelum reveal');
 assert(JSON.stringify(raw)===before,'Sanitiser tidak mengubah data asal');
 const revealed=clone(raw);revealed.room.status='reveal';
 const view=publicStageState(revealed);
 assert(view.question.correct===0&&view.question.explanation==='PRIVATE_EXPLANATION','Reveal: penerangan/jawapan dibenarkan');
 assert(view.distribution[0]===2,'Reveal: taburan agregat dibenarkan');
 assert(view.players[0].points===1000&&!('participant_code' in view.players[0]),'Ranking tanpa kod peserta');
 const pre=clone(revealed);pre.room.phase='pre';
 const preView=publicStageState(pre);
 assert(!('correct' in preView.question)&&!('explanation' in preView.question),'Pra tidak mendedahkan jawapan walaupun input mempunyai jawapan');
 assert(preView.players.every(p=>!('points' in p)),'Pra tiada mata pada TV');
 assert(Object.keys(preView.distribution).length===0,'Pra tiada taburan jawapan');
 const hidden=clone(revealed);hidden.room.settings.leaderboard=false;
 assert(publicStageState(hidden).players.every(p=>!('points' in p)),'Ranking OFF menyembunyikan mata');
 const helpers={questionMarkup:q=>`<div class="mock-question">${e(q.text)} ${q.options.map(e).join(' ')}</div>`,leaderboard:rows=>`<div class="mock-ranking">${rows.map(p=>e(p.name)+':'+p.rank).join('|')}</div>`,source:()=>'',joinLink:code=>'https://example.org/quiz/#/join/'+code};
 let html=screenMarkup(question,helpers);
 assert(!html.includes('Prestasi langsung')&&!html.includes('PEGAWAI SAHAJA'),'TV tiada monitor individu');
 assert(!html.includes('data-action="control"')&&!html.includes('#/report')&&!html.includes('#/dashboard'),'TV tiada kawalan / laporan / studio');
 assert(!html.includes('mock-ranking'),'Tiada ranking ketika peserta sedang menjawab');
 assert(html.includes('2</b> / 3 sudah menjawab'),'Kemajuan agregat dipaparkan');
 html=screenMarkup(view,helpers);
 assert(html.includes('Nadia:1')&&html.includes('Amir:1'),'Ranking seri mengekalkan tempat');
 assert(!html.includes('Belum jawab:'),'Belum jawab tidak masuk ranking');
 const final=clone(revealed);final.room.status='finished';
 html=screenMarkup(publicStageState(final),helpers);
 assert((html.match(/TEMPAT 1/g)||[]).length===2,'Dua pemenang seri menerima podium');
 assert(!html.includes('Belum jawab</h3>'),'Tiada podium untuk peserta kosong');
 const noRank=clone(final);noRank.room.settings.leaderboard=false;
 html=screenMarkup(publicStageState(noRank),helpers);
 assert(!html.includes('podium-card')&&!html.includes('mock-ranking'),'Ranking OFF: tiada podium / ranking akhir');
 assert(html.includes('Tiada ranking awam'),'Ranking OFF: mesej penyertaan');
 const preFinal=clone(final);preFinal.room.phase='pre';
 html=screenMarkup(publicStageState(preFinal),helpers);
 assert(!html.includes('podium-card')&&!html.includes('mock-ranking'),'Pra tamat tiada pemenang');
 const lobby=clone(raw);lobby.room.status='lobby';
 const lv=publicStageState(lobby);html=screenMarkup(lv,helpers);
 assert(lv.question===null,'Lobi tidak membawa soalan');
 assert(html.includes('id="qr"')&&html.includes('1234ABCD'),'Lobi mempunyai QR dan kod');
 assert(!html.includes('SECRET')&&!html.includes('Mulakan kuiz'),'Lobi TV tiada kod peserta / kawalan mula');
 const evil=clone(lobby);evil.room.title='<script>bad()</script>';evil.players[0].name='<img onerror=bad()>';
 html=screenMarkup(publicStageState(evil),helpers);
 assert(!html.includes('<script>')&&!html.includes('<img onerror='),'Tajuk dan nama di-escape');
 const home=participantHome('1234ABCD','Hafiz','',false);
 assert(!home.includes('Studio Pegawai')&&!home.includes('#/dashboard')&&!home.includes('pegawai.html'),'Halaman peserta tiada pautan pegawai');
 assert(home.includes('data-form="join"')&&home.includes('name="participant"'),'Borang penyertaan dan padanan pra kekal');
 assert(!home.includes('MOD DEMO')&&participantHome('','','',true).includes('MOD DEMO'),'Label demo jujur');
 assert(participantHome('\" autofocus onfocus=x','<script>','','').includes('&quot; autofocus'),'Input borang di-escape');
 assert(projectionGuide().includes('Extend')&&projectionGuide().includes('Mirror'),'Panduan dua paparan disertakan');
 const notice=hostDisplayNotice();
 assert(notice.includes('Ini panel pegawai')&&notice.includes('data-action="display-help"'),'Panel pegawai ada peringatan tayangan dan bantuan');
 assert(!html.includes('host-display-notice'),'Panduan kawalan tidak muncul pada TV');
 const ranked=rankRows([{name:'A',points:1,correct:1,ms:1},{name:'B',points:1,correct:1,ms:1},{name:'C',points:0,correct:0,ms:2}]);
 assert(ranked.map(p=>p.rank).join(',')==='1,1,3','Peraturan ranking asal kekal');
 return {checks:names.length,names};
}
